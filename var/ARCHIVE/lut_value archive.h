    private : 
        static const uint8_t DiffList[4][153];
        static const uint8_t PartialGreyList[4][153];


    public : 
        Lut() { UpdateLut(0*25);}

        void UpdateLut(int temperature)
        {
            int index = 3;
            if(temperature < 36){ index = 2; }
            if(temperature < 30){ index = 1; }
            if(temperature < 20){ index = 0; }
            printf("Index: %d\n", index);
            Diff = DiffList[index];
            PartialGrey = PartialGreyList[index];
        }

